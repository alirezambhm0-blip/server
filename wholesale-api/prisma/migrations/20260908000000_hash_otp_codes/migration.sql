-- =====================================================
-- Migration: P1-2 — حذف ذخیره‌سازی plaintext کد OTP
-- =====================================================
-- هدف: کد OTP نباید به‌صورت متن خام در دیتابیس باشد.
--
-- این migration دو کار می‌کند:
--   1) تغییر نام ستون "code" به "codeHash"
--   2) پاک‌سازی رکوردهای plaintext موجود
--
-- چرا تغییر نام و نه افزودن ستون جدید؟
--   ممیزی نشان داد کد OTP در دقیقاً یک نقطه نوشته می‌شود
--   (auth.service.ts → otp.upsert) و در دقیقاً یک نقطه خوانده می‌شود
--   (auth.service.ts → مقایسه در verifyOtp). بنابراین هیچ مسیر جایگزینی
--   وجود ندارد و تغییر نام، کامل و بدون باقی‌مانده است.
--   تغییر نام همچنین از نوشتن سهوی مقدار خام در آینده جلوگیری می‌کند.
-- =====================================================

-- ۱) تغییر نام ستون
-- توجه: نام ستون‌های این پروژه CamelCase با نقل‌قول است (بدون @map سطح فیلد)،
-- پس نام جدید نیز بدون @map و به‌صورت "codeHash" خواهد بود.
ALTER TABLE "otps" RENAME COLUMN "code" TO "codeHash";

-- ۲) پاک‌سازی رکوردهای plaintext موجود
--
-- چرا حذف و نه تبدیل (backfill)؟
--   تبدیل یک مقدار plaintext به bcrypt verifier نیازمند خواندن همان plaintext است.
--   اگرچه در لحظهٔ migration هنوز در دسترس است، ولی:
--     • کد OTP یک state موقتِ احراز هویت است با TTL دقیقاً ۲ دقیقه
--       (OTP_CONFIG.CODE_TTL_MS = 2 * 60 * 1000)
--     • هیچ دادهٔ کسب‌وکاری یا تاریخی در این جدول نیست
--     • هیچ کلید خارجی به این جدول ارجاع نمی‌دهد (مدل Otp هیچ relation ندارد)
--   بنابراین هر رکورد موجود یا همین حالا منقضی است یا حداکثر تا ۲ دقیقهٔ دیگر
--   منقضی می‌شود. حذف آن‌ها قوی‌ترین تضمین امنیتی را می‌دهد:
--
--       ▶ پس از اعمال این migration، هیچ مقدار plaintext در جدول otps باقی نمی‌ماند.
--
-- اثر روی کاربر: کاربرانی که در همان لحظهٔ deploy کد در دست دارند،
-- پیام «کد تایید نامعتبر است یا برای شما ارسال نشده است» می‌گیرند و
-- کافی است کد جدید درخواست دهند. با توجه به TTL دو دقیقه‌ای، این اثر
-- ناچیز و موقتی است.
DELETE FROM "otps";
